//While and DO While loops


//While loop

let i = 0;
while (i < 5) {
    console.log(i);
    i++;
}//This will output 0, 1, 2, 3, 4 as the loop continues until i is no longer less than 5.

//Do While loop

let j = 0;
do {
    console.log(j);
    j++;
} while (j < 5);//This will output 0, 1, 2, 3, 4 as the loop continues until j is no longer less than 5.

